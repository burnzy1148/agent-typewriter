// Bundles the modules the Claude Code plugin shares with the extension into
// claude-code/hooks/core.mjs, and their declarations into core.d.mts. A plugin
// may import only files in its own folder and installs from git with no build
// step, so both are committed; CI checks they are up to date. The neutral
// platform doubles as the shared-core check: a shared module that pulls in
// `vscode` or a Node built-in fails here.

import { build } from 'esbuild';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const CORE_ENTRY = `export { planHunks, authoringOrder, normalizeEol, type Hunk } from './src/planner';
export { typingChunkEnd, backspaceStep } from './src/typingChunks';
export { Timeline, type ChangeEvent, type NewChangeEvent } from './src/timeline';
`;

const HEADER = `// Generated by scripts/build-claude-code.mjs from src/planner.ts,
// src/typingChunks.ts and src/timeline.ts with what they import (and the diff
// package, BSD-3-Clause). Do not edit: change those files and run
// \`npm run build:claude-code\`.`;

const TYPES_HEADER = `// Generated by scripts/build-claude-code.mjs: the declarations of core.mjs,
// from the ones tsc emits for each module it bundles. Do not edit: change
// those modules and run \`npm run build:claude-code\`.`;

/** Bundles `entry` (module source, resolved from the repository root) to `outfile`, and its declarations to `typesfile`. */
export async function buildCore({
  entry = CORE_ENTRY,
  outfile = resolve(root, 'claude-code/hooks/core.mjs'),
  typesfile = outfile.replace(/\.mjs$/, '.d.mts'),
} = {}) {
  await build({
    stdin: { contents: entry, resolveDir: root, sourcefile: 'claude-code-core.ts', loader: 'ts' },
    absWorkingDir: root,
    bundle: true,
    platform: 'neutral',
    format: 'esm',
    target: 'es2022',
    mainFields: ['module', 'main'],
    banner: { js: HEADER },
    legalComments: 'inline',
    outfile,
    logLevel: 'warning',
  });
  buildTypes(entry, typesfile);
}

/** Runs the repository's tsc with the compiler options tsconfig.json sets. */
function tsc(args) {
  const options = ['--ignoreConfig', '--target', 'es2022', '--module', 'preserve', '--moduleResolution', 'bundler', '--strict', '--newLine', 'lf'];
  execFileSync(process.execPath, [resolve(root, 'node_modules/typescript/bin/tsc'), ...options, ...args], { cwd: root, stdio: 'inherit' });
}

/** Names a declaration file declares at its top level. */
const DECLARED = /^(?:declare )?(?:abstract )?(?:class|interface|type|function|const|let|var|enum|namespace) (\w+)/gm;

/**
 * Declarations for `entry` as one module. tsc writes a file per module, so
 * their declarations are joined, their imports of one another dropped, and
 * only the entry's names exported; the rest stay local to the file.
 */
function buildTypes(entry, typesfile) {
  const modules = [...entry.matchAll(/ from '\.\/(src\/[^']+)';/g)].map((m) => `${m[1]}.ts`);
  const out = mkdtempSync(join(tmpdir(), 'claude-code-core-'));
  try {
    tsc(['--declaration', '--emitDeclarationOnly', '--types', 'node', '--skipLibCheck', '--rootDir', 'src', '--outDir', out, ...modules]);
    const owners = new Map();
    let body = '';
    for (const file of readdirSync(out).filter((f) => f.endsWith('.d.ts')).sort()) {
      const name = `src/${file.replace(/\.d\.ts$/, '.ts')}`;
      const text = readFileSync(join(out, file), 'utf8')
        .replace(/^import [^;]* from '\.[^']*';\n/gm, '')
        .replace(/^export \{\};\n/gm, '')
        .replace(/^export (?=declare |interface |type \w)/gm, '');
      const left = /^(?:import|export|\/\/\/).*/m.exec(text);
      if (left) throw new Error(`${name}: cannot bundle \`${left[0]}\`; the plugin can import only its own files.`);
      for (const [, id] of text.matchAll(DECLARED)) {
        // Interfaces and functions of one name merge, so two modules' would not fail the check below.
        if (owners.has(id) && owners.get(id) !== name) throw new Error(`${id} is declared in both ${owners.get(id)} and ${name}.`);
        owners.set(id, name);
      }
      body += `\n// ${name}\n\n${text}`;
    }
    writeFileSync(typesfile, `${TYPES_HEADER}\n${body}\n${entry.replace(/ from '[^']*';/g, ';')}`);
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
  // The file stands on its own: it is checked without Node's types or any other file.
  tsc(['--noEmit', '--lib', 'es2022', '--types', '', typesfile]);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  buildCore().catch((err) => {
    // esbuild has already reported its own errors.
    if (!err.errors) console.error(err.message);
    process.exit(1);
  });
}
