// Bundles the modules the Claude Code plugin shares with the extension into
// claude-code/hooks/core.mjs. A plugin may import only files in its own folder
// and installs from git with no build step, so the bundle is committed; CI
// checks it is up to date. The neutral platform doubles as the shared-core
// check: a shared module that pulls in `vscode` or a Node built-in fails here.

import { build } from 'esbuild';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const CORE_ENTRY = `export { planHunks, authoringOrder, normalizeEol, type Hunk } from './src/planner';
export { typingChunkEnd, backspaceStep } from './src/typingChunks';
`;

const HEADER = `// Generated by scripts/build-claude-code.mjs from src/planner.ts and
// src/typingChunks.ts (with the diff package, BSD-3-Clause). Do not edit:
// change those files and run \`npm run build:claude-code\`.`;

/** Bundles `entry` (module source, resolved from the repository root) to `outfile`. */
export async function buildCore({ entry = CORE_ENTRY, outfile = resolve(root, 'claude-code/hooks/core.mjs') } = {}) {
  await build({
    stdin: { contents: entry, resolveDir: root, sourcefile: 'claude-code-core.ts', loader: 'ts' },
    absWorkingDir: root,
    bundle: true,
    platform: 'neutral',
    format: 'esm',
    target: 'es2022',
    mainFields: ['module', 'main'],
    banner: { js: HEADER },
    legalComments: 'inline',
    outfile,
    logLevel: 'warning',
  });
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  buildCore().catch(() => process.exit(1));
}
